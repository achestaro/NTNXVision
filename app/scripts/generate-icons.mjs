// Rasterise the app icon art (app/build/art/*.svg) into every format the app ships:
//   npm run icons            (needs the Playwright Chromium already used by the screenshots)
// - app/build/icon.png (1024) and app/build/icons/<n>x<n>.png: the full-bleed tile.
// - app/build/icon.ico: 16 to 256 px, PNG-compressed entries.
// - app/build/icon.icns (macOS only, iconutil): the tile inset to Apple's 824 px grid.
// - src/main/trayIcons.ts: 32 px tray icon and the macOS menu-bar template (black + alpha).
// - src/renderer/assets/logo.svg (favicon) is a copy of icon.svg.
// Edit the SVGs, re-run, commit the outputs.
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const art = (name) => readFileSync(join(app, 'build', 'art', name), 'utf-8');
const icon = art('icon.svg');
const template = art('tray-template.svg');
// macOS: the 1024 canvas holds an 824 px tile centred (Apple's icon grid), corners scaled to match.
const macIcon = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><g transform="translate(100 100) scale(0.8046875)">${icon.replace(/^<svg[^>]*>|<\/svg>$/g, '')}</g></svg>`;

const browser = await chromium.launch().catch(() => chromium.launch({ channel: 'chrome' }));
const page = await browser.newPage();
async function png(svg, size) {
  await page.setViewportSize({ width: size, height: size });
  const body = svg.replace(/<svg /, `<svg style="display:block;width:${size}px;height:${size}px" `);
  await page.setContent(`<html><body style="margin:0;background:transparent">${body}</body></html>`);
  return page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } });
}

const build = join(app, 'build');
mkdirSync(join(build, 'icons'), { recursive: true });
writeFileSync(join(build, 'icon.png'), await png(icon, 1024));
for (const n of [16, 24, 32, 48, 64, 128, 256, 512, 1024]) writeFileSync(join(build, 'icons', `${n}x${n}.png`), await png(icon, n));

// ICO with PNG entries (Windows Vista and later).
const icoSizes = [16, 24, 32, 48, 64, 128, 256];
const images = [];
for (const n of icoSizes) images.push(await png(icon, n));
const header = Buffer.alloc(6 + 16 * images.length);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(images.length, 4);
let offset = header.length;
images.forEach((img, i) => {
  const n = icoSizes[i];
  const at = 6 + 16 * i;
  header.writeUInt8(n >= 256 ? 0 : n, at);
  header.writeUInt8(n >= 256 ? 0 : n, at + 1);
  header.writeUInt16LE(1, at + 4);
  header.writeUInt16LE(32, at + 6);
  header.writeUInt32LE(img.length, at + 8);
  header.writeUInt32LE(offset, at + 12);
  offset += img.length;
});
writeFileSync(join(build, 'icon.ico'), Buffer.concat([header, ...images]));

if (process.platform === 'darwin') {
  const dir = join(mkdtempSync(join(tmpdir(), 'ntnxicon-')), 'icon.iconset');
  mkdirSync(dir);
  for (const n of [16, 32, 128, 256, 512]) {
    writeFileSync(join(dir, `icon_${n}x${n}.png`), await png(macIcon, n));
    writeFileSync(join(dir, `icon_${n}x${n}@2x.png`), await png(macIcon, n * 2));
  }
  execFileSync('iconutil', ['-c', 'icns', dir, '-o', join(build, 'icon.icns')]);
  rmSync(dirname(dir), { recursive: true, force: true });
} else {
  console.warn('icon.icns not rebuilt: iconutil is macOS only.');
}

const tray = (await png(icon, 32)).toString('base64');
const mac = (await png(template, 32)).toString('base64');
writeFileSync(
  join(app, 'src', 'main', 'trayIcons.ts'),
  `// Tray / menu bar icons, embedded so the compiled main process needs no asset files.
// macOS: a 32 x 32 template image (black + alpha, shown at 16 pt, tinted by the menu bar).
// Windows and Linux: the 32 x 32 app icon.
// Generated by scripts/generate-icons.mjs from build/art/: do not edit by hand.

export const MAC_TEMPLATE_PNG =
  '${mac}';
export const APP_ICON_PNG =
  '${tray}';
`,
);
copyFileSync(join(build, 'art', 'icon.svg'), join(app, 'src', 'renderer', 'assets', 'logo.svg'));
await browser.close();
console.log('icons written');
